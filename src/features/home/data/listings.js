export const searchableOptions = Array.from(
  new Set(
    listings.flatMap((listing) => [
      listing.year,
      listing.brand,
      listing.color,
      listing.bodyStyle,
      listing.type === "auction" ? "Auction" : "Classified",
    ]),
  ),
).sort((left, right) => left.localeCompare(right));

export function buildListingSearchIndex(listing) {
  return [
    listing.year,
    listing.brand,
    listing.color,
    listing.bodyStyle,
    listing.type,
    listing.type === "auction" ? "auction" : "classified",
    listing.title,
    listing.description,
    listing.location,
  ]
    .join(" ")
    .toLowerCase();
}
